#[cfg(test)]
mod apply_tests {
    //! Step-5 commit 1 pins for [Data::apply]: the apply/check/rollback gate
    //! rolls a broken landing back to a bit-identical pre-op state and reports it
    //! precisely; a `GlobalUpdate` carrying logically impossible (duplicated-id)
    //! data comes back as [InvalidOp::Logic], rolled back.

    use crate::ids::{Id, PeriodId, StudentId, SubjectId, WeekPatternId};
    use crate::ops::{
        AnnotatedOp, AnnotatedPeriodOp, AnnotatedStudentOp, AnnotatedSubjectOp, AssignmentOp, Op,
        PeriodOp, StudentOp, SubjectOp,
    };
    use crate::students::Student;
    use crate::subjects::Subject;
    use crate::week_patterns::WeekPattern;
    use crate::{Data, Error, FixableInvariant, InnerData, InvalidOp, Reference, StudentRefSite};
    use collomatique_state::InMemoryData;
    use std::collections::BTreeSet;

    /// Applies a (valid) op through the gate and returns its annotated form,
    /// so callers can read back the freshly issued ids.
    fn apply(data: &mut Data, op: Op) -> AnnotatedOp {
        let (annotated, _) = data.annotate(op);
        data.apply(&annotated).expect("valid op should apply");
        annotated
    }

    /// The smallest state where a student is referenced by an assignments row:
    /// one period, one subject running on it, one student assigned. Returns
    /// `(data, period, subject, student)`.
    fn data_with_assignment() -> (Data, PeriodId, SubjectId, StudentId) {
        let mut data = Data::default();
        let period = match apply(&mut data, Op::Period(PeriodOp::AddFront)) {
            AnnotatedOp::Period(AnnotatedPeriodOp::AddFront(p)) => p,
            other => panic!("unexpected annotated op {other:?}"),
        };
        let subject = match apply(
            &mut data,
            Op::Subject(SubjectOp::AddAfter(None, Subject::default())),
        ) {
            AnnotatedOp::Subject(AnnotatedSubjectOp::AddAfter(s, _, _)) => s,
            other => panic!("unexpected annotated op {other:?}"),
        };
        let student = match apply(&mut data, Op::Student(StudentOp::Add(Student::default()))) {
            AnnotatedOp::Student(AnnotatedStudentOp::Add(u, _)) => u,
            other => panic!("unexpected annotated op {other:?}"),
        };
        apply(
            &mut data,
            Op::Assignment(AssignmentOp::SetRow(
                period,
                subject,
                BTreeSet::from([student]),
            )),
        );
        (data, period, subject, student)
    }

    #[test]
    fn apply_invariant_breaking_op_rolls_back_and_reports() {
        let (mut data, _period, _subject, student) = data_with_assignment();
        let before = data.clone();

        // Removing a still-referenced student lands a dangling assignments FK
        // (the Remove scans are stripped in `force_apply`); the gate must roll the
        // state back and report it as an Invariants error.
        let (remove, _) = data.annotate(Op::Student(StudentOp::Remove(student)));
        let err = data.apply(&remove).unwrap_err();

        match err {
            Error::BrokenInvariants(set) => assert!(
                set.iter()
                    .any(|f| matches!(f, FixableInvariant::DanglingFk(_))),
                "expected a dangling-FK report, got {set:?}"
            ),
            other => panic!("expected BrokenInvariants, got {other:?}"),
        }
        assert!(
            data == before,
            "a rolled-back apply must leave the state bit-identical"
        );
    }

    #[test]
    fn apply_global_update_with_duplicated_id_errors_logic_and_rolls_back() {
        let mut data = Data::default();
        let before = data.clone();

        // A corrupt inner: a student and a week pattern sharing raw id 1 — a
        // duplicated-id LogicError. Through the gate this rolls back and surfaces
        // as InvalidOp::Logic (post-sealing the only route into that arm).
        let mut corrupt = InnerData::default();
        let student = unsafe { StudentId::new(1) };
        let pattern = unsafe { WeekPatternId::new(1) };
        corrupt
            .params
            .students
            .student_map
            .insert(student, Student::default());
        corrupt.params.week_patterns.week_pattern_map.insert(
            pattern,
            WeekPattern {
                name: "P".into(),
                excluded_weeks: BTreeSet::new(),
            },
        );

        let op = AnnotatedOp::GlobalUpdate(corrupt);
        let err = data.apply(&op).unwrap_err();

        assert!(
            matches!(err, Error::InvalidOp(InvalidOp::Logic(ref set)) if !set.is_empty()),
            "expected a non-empty Logic error, got {err:?}"
        );
        assert!(
            data == before,
            "a rolled-back GlobalUpdate must leave the state bit-identical"
        );
    }

    #[test]
    fn apply_set_row_with_a_dead_payload_student_is_a_checker_rejection() {
        let (mut data, period, subject, student) = data_with_assignment();
        let before = data.clone();

        // A student id nobody holds. `SetRow` prechecks its *address* — the
        // `(period, subject)` key, which an empty payload would clear without
        // leaving the FK net anything to look at — and nothing else. The
        // payload students are op content: the op lands, the checker walks the
        // row it wrote, and the dangling reference is what stops it. This is
        // one tier down from where the payload sweep used to catch it, and it
        // is the same tier `ColloscopeOp::SetGroupList`'s placements have always
        // been reported at.
        let ghost = unsafe { StudentId::new(9_999) };
        let (set_row, _) = data.annotate(Op::Assignment(AssignmentOp::SetRow(
            period,
            subject,
            BTreeSet::from([student, ghost]),
        )));
        let err = data.apply(&set_row).unwrap_err();

        assert_eq!(
            err,
            Error::BrokenInvariants(BTreeSet::from([FixableInvariant::DanglingFk(
                Reference::Student {
                    target: ghost,
                    site: StudentRefSite::AssignmentsStudent { period, subject },
                }
            )])),
            "the dead payload student is reported by the FK net — and it is the \
             only break, since the convergence checks skip a student that does \
             not resolve"
        );
        assert!(
            data == before,
            "a rolled-back apply must leave the state bit-identical"
        );
    }
}

#[cfg(test)]
mod construction_boundary_tests {
    //! Pins for the [Data] construction boundary — the decode trust boundary of
    //! the design record's G.4. [Data::from_inner_data] is the one door through
    //! which data built *outside* this crate enters, so both of its rejection
    //! arms ([FromInnerDataError::Logic] and
    //! [FromInnerDataError::BrokenInvariants]) are load-bearing: a broken state
    //! must never exist outside the apply/check/rollback primitive. Both arms
    //! were constructed but never exercised before this module.
    //!
    //! The third test pins the [Data]-level companion of the checker, the
    //! id-issuer high-water assertion. It fires on the *accepted* path of the
    //! gate, so the only way to reach it is a [Data] whose issuer was never
    //! built from its own ids — which in turn needs the crate-private field, and
    //! is why this module is in-crate rather than in `tests/`.

    use crate::ids::{Id, SlotId, StudentId, SubjectId, TeacherId, WeekId};
    use crate::ops::{AnnotatedOp, AnnotatedStudentOp};
    use crate::slots::{Slot, Slots};
    use crate::students::Student;
    use crate::subjects::Subject;
    use crate::{Data, FromInnerDataError, IdIssuer, InnerData};
    use collomatique_state::InMemoryData;
    use std::collections::BTreeSet;

    /// A minimal well-formed slot on the given subject/teacher, mirroring the
    /// invariants-module fixture: no week pattern, Monday 8:00.
    fn test_slot(subject_id: SubjectId, teacher_id: TeacherId) -> Slot {
        Slot {
            subject_id,
            teacher_id,
            start_time: collomatique_time::SlotStart {
                weekday: chrono::Weekday::Mon.into(),
                start_time: collomatique_time::WholeMinuteTime::new(
                    chrono::NaiveTime::from_hms_opt(8, 0, 0).unwrap(),
                )
                .unwrap(),
            },
            extra_info: String::new(),
            week_pattern: None,
            cost: 0,
        }
    }

    #[test]
    fn from_inner_data_rejects_logically_impossible_data() {
        // A stored *empty* colloscope interrogation row: the canonical form of
        // "no interrogation there" is an absent row, so a present empty one is
        // logically impossible. No production surface can build it — hence the
        // `forge_*` door — but a hand-edited or hostile file can.
        let mut inner_data = InnerData::default();
        let slot = unsafe { SlotId::new(1) };
        let week = unsafe { WeekId::new(2) };
        inner_data
            .colloscope
            .forge_interrogation_row(slot, week, BTreeSet::new());

        let err = Data::from_inner_data(inner_data).unwrap_err();

        assert!(
            matches!(err, FromInnerDataError::Logic(ref set) if !set.is_empty()),
            "expected a non-empty Logic error, got {err:?}"
        );
    }

    #[test]
    fn from_inner_data_rejects_broken_invariants() {
        // One subject with one slot, and a teacher id that names nobody: a
        // dangling FK. Unlike the logic tier this one *is* fixable — but a
        // loaded file has no cascade behind it, so the load fails outright.
        let mut inner_data = InnerData::default();
        let subject = unsafe { SubjectId::new(1) };
        let slot = unsafe { SlotId::new(2) };
        let teacher = unsafe { TeacherId::new(3) };
        inner_data
            .params
            .subjects
            .ordered_subject_list
            .insert_at(0, subject, Subject::default())
            .expect("a fresh list has no id to clobber");
        inner_data.params.slots =
            Slots::from_subject_rows([(subject, vec![(slot, test_slot(subject, teacher))])])
                .expect("one slot cannot duplicate an id");

        let err = Data::from_inner_data(inner_data).unwrap_err();

        assert!(
            matches!(err, FromInnerDataError::BrokenInvariants(ref set) if !set.is_empty()),
            "expected a non-empty BrokenInvariants error, got {err:?}"
        );
    }

    #[test]
    #[should_panic(expected = "not greater than all internal ids")]
    fn an_issuer_lagging_behind_the_data_panics_on_the_accepted_path() {
        // `from_inner_data` builds the issuer *from* the data's ids, so it can
        // never produce this pairing; the struct literal is the only route, and
        // it stands in for the real trigger named in [Data::apply]'s doc — an
        // `AnnotatedOp` transplanted from another `Data` instance, whose ids
        // this issuer never handed out.
        let mut inner_data = InnerData::default();
        let student = unsafe { StudentId::new(5) };
        inner_data
            .params
            .students
            .student_map
            .insert(student, Student::default());

        let mut data = Data {
            id_issuer: IdIssuer::new(std::iter::empty()).expect("an empty issuer is valid"),
            inner_data,
        };

        // A valid op on a valid document: the precheck passes, the landing
        // breaks nothing, and the gate reaches its `Ok` arm — where the
        // high-water assertion catches the lagging issuer.
        let op = AnnotatedOp::Student(AnnotatedStudentOp::Update(student, Student::default()));
        let _ = data.apply(&op);
    }
}
