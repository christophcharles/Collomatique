/// Internal structure to store the data for [Data]
///
/// We have `data1 == data2` if and only if their internal
/// data is the same. This means they would lead to the same
/// file on disk. But the internal id issuer might have a different
/// state.
///
/// [InnerData] represents this actual 'on-disk' data so we can
/// directly use `derive(PartialEq, Eq)` with it. The implementation
/// of [Eq] and [PartialEq] for [Data] relies on it.
#[derive(Debug, Clone, PartialEq, Eq, Default, ContentOrd)]
pub struct InnerData {
    pub params: colloscope_params::Parameters,
    pub colloscope: colloscopes::Colloscope,
    pub export_config: export_config::ExportConfig,
}

impl InnerData {
    fn ids(&self) -> impl Iterator<Item = u64> {
        self.params.ids()
    }
}

/// Complete data that can be handled in the colloscope
///
/// This [Data] structure contains all the data that can
/// be manipulated in collomatique. It contains the list
/// of students, of teachers, the various interrogations,
/// a description of constraints etc. It also contains the
/// various colloscopes that have been generated or edited.
///
/// It cannot be modified or accessed directly. To the other
/// crates, this is an opaque type.
///
/// It does not necesserally correlate exactly to the data stored
/// on disk. This is to allow versioning.
#[derive(Clone, Debug, ContentOrd)]
pub struct Data {
    // The document order does not see the issuer: two `Data` with equal
    // inner data are content-equivalent even when their issuers differ —
    // the same quotient the hand-written `PartialEq` below takes.
    #[ord(ignore)]
    id_issuer: IdIssuer,
    inner_data: InnerData,
}

impl PartialEq for Data {
    fn eq(&self, other: &Self) -> bool {
        self.inner_data == other.inner_data
    }
}

impl Eq for Data {}

/// Errors of [Data::force_apply]: only op preconditions (the carve-out subset —
/// no-clobber, op-target existence, positions/anchors), never invariants.
/// Invariant breaks are the caller's business via
/// [InnerData::broken_invariants] plus rollback.
///
/// The forced `GlobalUpdate` drops the pre-gate and is infallible, so this enum
/// has no `GlobalUpdate` arm. Each arm wraps a per-domain `*PrecheckError` (the
/// carve-out subset of op preconditions); the three value-only domains carry
/// empty enums.
#[derive(Clone, Debug, PartialEq, Eq, Error)]
pub enum PrecheckError {
    #[error(transparent)]
    Student(#[from] StudentPrecheckError),
    #[error(transparent)]
    Period(#[from] PeriodPrecheckError),
    #[error(transparent)]
    Week(#[from] WeekPrecheckError),
    #[error(transparent)]
    Subject(#[from] SubjectPrecheckError),
    #[error(transparent)]
    Teacher(#[from] TeacherPrecheckError),
    #[error(transparent)]
    Assignment(#[from] AssignmentPrecheckError),
    #[error(transparent)]
    WeekPattern(#[from] WeekPatternPrecheckError),
    #[error(transparent)]
    Slot(#[from] SlotPrecheckError),
    #[error(transparent)]
    Incompat(#[from] IncompatPrecheckError),
    #[error(transparent)]
    GroupList(#[from] GroupListPrecheckError),
    #[error(transparent)]
    Settings(#[from] SettingsPrecheckError),
    #[error(transparent)]
    Pairing(#[from] PairingPrecheckError),
    #[error(transparent)]
    SlotPairing(#[from] SlotPairingPrecheckError),
    #[error(transparent)]
    Balancing(#[from] BalancingPrecheckError),
    #[error(transparent)]
    Colloscope(#[from] ColloscopePrecheckError),
    #[error(transparent)]
    ExportConfig(#[from] ExportConfigPrecheckError),
}

/// The unresolvable tier of the gate's error surface: bad op input. Both the
/// carve-out prechecks (design doc §4) and the logic tier live here — an op
/// whose payload would land logically impossible rows is an invalid op.
///
/// [InvalidOp::Logic] stays reachable only from data built outside this crate
/// (`GlobalUpdate` payloads, decode): ordinary elementary ops cannot construct
/// logically impossible rows since the value types were sealed.
#[derive(Clone, Debug, PartialEq, Eq, Error)]
pub enum InvalidOp {
    /// Bad op input (no-clobber, dangling target, bad position/anchor).
    /// The state was never touched.
    #[error(transparent)]
    Precheck(#[from] PrecheckError),
    /// The op would land logically impossible rows; rolled back.
    #[error("the operation would leave logically impossible data: {}", format_error_set(.0))]
    Logic(BTreeSet<LogicError>),
}

/// Error surface of the apply/check/rollback gate ([Data::apply]): the shared
/// two-tier [collomatique_state::ApplyError] instantiated with this crate's
/// vocabulary. [collomatique_state::ApplyError::InvalidOp] is bad op input
/// (never resolvable); [collomatique_state::ApplyError::BrokenInvariants] is
/// what the cascade resolves (at step 5 it is simply an error).
pub type Error = collomatique_state::ApplyError<InvalidOp, FixableInvariant>;

/// Lets the gate keep writing `self.force_apply(op)?`.
impl From<PrecheckError> for Error {
    fn from(e: PrecheckError) -> Self {
        collomatique_state::ApplyError::InvalidOp(InvalidOp::Precheck(e))
    }
}

/// Itemises a set of errors through each entry's own [std::fmt::Display] so a
/// UI dialog can surface a meaningful message without learning the vocabulary.
fn format_error_set<T: std::fmt::Display>(set: &BTreeSet<T>) -> String {
    set.iter().map(T::to_string).collect::<Vec<_>>().join("; ")
}

/// Error surface of [Data::from_inner_data] — rebuilding a [Data] from a loaded
/// [InnerData]. A loaded file must be fully valid (broken states never exist
/// outside the apply/check/rollback primitive), so any non-clean checker result
/// is an error here.
#[derive(Clone, Debug, PartialEq, Eq, Error)]
pub enum FromInnerDataError {
    #[error(transparent)]
    IdError(#[from] tools::IdError),
    /// The loaded data would leave logically impossible rows.
    #[error("the loaded data is logically impossible: {}", format_error_set(.0))]
    Logic(BTreeSet<LogicError>),
    /// The loaded data breaks fixable invariants (dangling references or broken
    /// convergence facts).
    #[error("the loaded data breaks invariants: {}", format_error_set(.0))]
    BrokenInvariants(BTreeSet<FixableInvariant>),
}

impl InMemoryData for Data {
    type OriginalOperation = Op;
    type AnnotatedOperation = AnnotatedOp;
    type NewInfo = Option<NewId>;
    type InvalidOp = InvalidOp;
    type Invariant = FixableInvariant;

    fn annotate(&mut self, op: Op) -> (AnnotatedOp, Option<NewId>) {
        AnnotatedOp::annotate(op, &mut self.id_issuer)
    }

    /// The apply/check/rollback gate: snapshot, [Data::force_apply], check with
    /// [InnerData::broken_invariants], and roll back on any breakage.
    ///
    /// On the accepted path the id-issuer high-water assert
    /// (`Data::assert_id_issuer_high_water`) is the surviving [Data]-level
    /// companion of the checker. It cannot fire through the [Manager] surface:
    /// `annotate` draws every fresh id from this issuer, and the `GlobalUpdate`
    /// annotate arm absorbs foreign payload ids up front via
    /// `IdIssuer::skip_to_id`. Its only trigger is an [AnnotatedOp] transplanted
    /// from another [Data] instance through this raw entry point — a caller bug,
    /// hence a panic rather than an error arm.
    fn apply(
        &mut self,
        op: &Self::AnnotatedOperation,
    ) -> std::result::Result<
        Self::AnnotatedOperation,
        collomatique_state::ApplyError<Self::InvalidOp, Self::Invariant>,
    > {
        // Snapshot everything an op could conceivably touch. `force_apply` never
        // uses the id issuer today (ids are issued in `annotate`), but the issuer
        // is a single counter — snapshotting it keeps rollback total even if a
        // later change to a `force_apply_*` copy starts touching it. Note what it
        // must *not* undo: `annotate` runs before `apply` and its issued ids
        // stay burned on failure, exactly as today — history ids are never reused.
        let snapshot = self.inner_data.clone();
        let issuer_snapshot = self.id_issuer.clone();

        // Precheck failures return before any mutation (by construction of the
        // `force_apply_*` copies); the restore below makes that a mechanism
        // rather than a 16-file discipline — a copy that ever mutated before
        // erroring would still leave the state bit-identical. The snapshot is
        // already in hand for the checker arms, so this costs nothing on the
        // accepted path. `e.into()` is the same conversion the `?` used to
        // apply (`From<PrecheckError> for Error`), so the error value is
        // unchanged.
        let backward = match self.force_apply(op) {
            Ok(backward) => backward,
            Err(e) => {
                self.inner_data = snapshot;
                self.id_issuer = issuer_snapshot;
                return Err(e.into());
            }
        };

        match self.inner_data.broken_invariants() {
            Err(logic) => {
                self.inner_data = snapshot;
                self.id_issuer = issuer_snapshot;
                Err(collomatique_state::ApplyError::InvalidOp(InvalidOp::Logic(
                    logic,
                )))
            }
            Ok(fixable) if !fixable.is_empty() => {
                self.inner_data = snapshot;
                self.id_issuer = issuer_snapshot;
                Err(collomatique_state::ApplyError::BrokenInvariants(fixable))
            }
            Ok(_empty) => {
                self.assert_id_issuer_high_water();
                Ok(backward)
            }
        }
    }
}

impl Data {
    /// Applies `op` without checking invariants. Carve-out preconditions still
    /// hold (no-clobber, op-target existence, positions/anchors) and surface
    /// as [PrecheckError]; a failed call leaves the state
    /// unchanged. A *successful* call may leave the state invalid: the caller
    /// owns running the checker ([InnerData::broken_invariants]) and restoring a
    /// snapshot on failure.
    ///
    /// Each arm calls the corresponding `force_apply_*` (the carve-out-only
    /// domain writer). The `GlobalUpdate` arm has no invariant pre-gate — this
    /// *is* the force door — and there is no trailing panic net, since the state
    /// is allowed to be invalid here. It is the force half of the
    /// apply/check/rollback gate ([Data::apply]).
    pub fn force_apply(
        &mut self,
        op: &AnnotatedOp,
    ) -> std::result::Result<AnnotatedOp, PrecheckError> {
        let backward = match op {
            AnnotatedOp::Student(o) => AnnotatedOp::Student(self.force_apply_student(o)?),
            AnnotatedOp::Period(o) => AnnotatedOp::Period(self.force_apply_period(o)?),
            AnnotatedOp::Week(o) => AnnotatedOp::Week(self.force_apply_week(o)?),
            AnnotatedOp::Subject(o) => AnnotatedOp::Subject(self.force_apply_subject(o)?),
            AnnotatedOp::Teacher(o) => AnnotatedOp::Teacher(self.force_apply_teacher(o)?),
            AnnotatedOp::Assignment(o) => AnnotatedOp::Assignment(self.force_apply_assignment(o)?),
            AnnotatedOp::WeekPattern(o) => {
                AnnotatedOp::WeekPattern(self.force_apply_week_pattern(o)?)
            }
            AnnotatedOp::Slot(o) => AnnotatedOp::Slot(self.force_apply_slot(o)?),
            AnnotatedOp::Incompat(o) => AnnotatedOp::Incompat(self.force_apply_incompat(o)?),
            AnnotatedOp::Pairing(o) => AnnotatedOp::Pairing(self.force_apply_pairing(o)?),
            AnnotatedOp::SlotPairing(o) => {
                AnnotatedOp::SlotPairing(self.force_apply_slot_pairing(o)?)
            }
            AnnotatedOp::GroupList(o) => AnnotatedOp::GroupList(self.force_apply_group_list(o)?),
            AnnotatedOp::Settings(o) => AnnotatedOp::Settings(self.force_apply_settings(o)?),
            AnnotatedOp::Balancing(o) => AnnotatedOp::Balancing(self.force_apply_balancing(o)?),
            AnnotatedOp::Colloscope(o) => AnnotatedOp::Colloscope(self.force_apply_colloscope(o)?),
            AnnotatedOp::ExportConfig(o) => {
                AnnotatedOp::ExportConfig(self.force_apply_export_config(o)?)
            }
            AnnotatedOp::GlobalUpdate(new_inner_data) => {
                // no invariant pre-gate: this is the force door
                let old = std::mem::replace(&mut self.inner_data, new_inner_data.clone());
                AnnotatedOp::GlobalUpdate(old)
            }
        };
        // no panic net: the state is allowed to be invalid here
        Ok(backward)
    }
}

impl Data {
    /// USED INTERNALLY
    ///
    /// Asserts the id-issuer high-water invariant: the issuer's internal counter
    /// is strictly greater than every id currently live in the data, so a freshly
    /// issued id can never collide with an existing one.
    ///
    /// This is [Data]-level state (the issuer is deliberately not part of
    /// [InnerData]), so it cannot live in [InnerData::broken_invariants]; it is
    /// the surviving companion the apply/check/rollback gate ([Data::apply])
    /// runs on the accepted path.
    fn assert_id_issuer_high_water(&self) {
        let max_id = self.inner_data.ids().max();

        if let Some(id) = max_id {
            if id >= self.id_issuer.get_internal_counter() {
                panic!("IdIssuer internal counter is not greater than all internal ids");
            }
        }
    }
}

impl Default for Data {
    fn default() -> Self {
        Self::new()
    }
}

impl Data {
    /// Create a new [Data]
    ///
    /// This [Data] is basically empty and corresponds to the
    /// state of a new file
    pub fn new() -> Data {
        Self::from_inner_data(InnerData::default()).expect("Default data should be valid")
    }

    /// Create a new [Data] from existing data
    ///
    /// This will check the consistency of the data
    /// and will also do some internal checks, so this might fail.
    pub fn from_inner_data(inner_data: InnerData) -> Result<Data, FromInnerDataError> {
        // A loaded file must be fully valid: hard error on a logic breakage and
        // on any non-empty fixable set. Broken states never exist outside the
        // apply/check/rollback primitive.
        match inner_data.broken_invariants() {
            Err(logic) => return Err(FromInnerDataError::Logic(logic)),
            Ok(set) if !set.is_empty() => return Err(FromInnerDataError::BrokenInvariants(set)),
            Ok(_) => {}
        }

        let id_issuer = IdIssuer::new(inner_data.ids())?;

        let data = Data {
            id_issuer,
            inner_data,
        };

        // Data-level companion of the checker (the id issuer is not part of
        // InnerData, so broken_invariants cannot see it).
        data.assert_id_issuer_high_water();

        Ok(data)
    }

    /// Returns a non-mutable reference to internal data
    ///
    /// Elementary ops allow the edition of data. But between two ops
    /// you can inspect the current data via this function
    pub fn get_inner_data(&self) -> &InnerData {
        &self.inner_data
    }

    /// Similar to [Self::get_inner_data] but consumes the [Data] and returns
    /// an owned [InnerData]
    pub fn into_inner_data(self) -> InnerData {
        self.inner_data
    }
}

